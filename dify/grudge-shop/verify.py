"""Exercise REAL gateway + PowerContext, then save a portable evidence file."""
import json
import os
import argparse
from pathlib import Path
from urllib.request import Request, urlopen
from urllib.error import HTTPError
from uuid import uuid4

URL = os.environ.get('GATEWAY_URL', 'http://127.0.0.1:8765').rstrip('/')
TOKEN = os.environ.get('GATEWAY_TOKEN', '')

def post(path, payload, token=None):
    token = TOKEN if token is None else token
    req = Request(URL + path, json.dumps(payload, ensure_ascii=False).encode(),
                  {'Content-Type': 'application/json', 'Authorization': 'Bearer ' + token}, method='POST')
    with urlopen(req, timeout=40) as response:
        return json.load(response)

def main(argv=None):
    global URL, TOKEN
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--connection', type=Path, help='Private connection.json generated by run_local.py')
    parser.add_argument('--url', help='Override gateway URL, for example its public HTTPS endpoint')
    parser.add_argument('--output', type=Path, default=Path(__file__).parent / 'evidence/powercontext-roundtrip.json')
    parser.add_argument('--resume', type=Path, help='Recall the prior test player after an actual service restart.')
    args = parser.parse_args(argv)
    if args.connection:
        connection = json.loads(args.connection.read_text(encoding='utf-8'))
        URL = connection['gateway_url'].rstrip('/')
        TOKEN = connection['gateway_token']
    if args.url:
        URL = args.url.rstrip('/')
    if not TOKEN or TOKEN == 'REPLACE_WITH_GATEWAY_TOKEN':
        parser.error('Supply --connection .runtime/connection.json or set GATEWAY_TOKEN to your actual gateway token.')
    if args.resume:
        result = json.loads(args.resume.read_text(encoding='utf-8'))
        recovered = post('/recall', {'player_id': result['player_id'], 'query': '重启后回忆杂货铺'})
        assert recovered['scope_id'] == result['initial']['scope_id']
        assert recovered['status'] == 'ready' and '量子罐头' in recovered['content']
        result['restart_recall'] = recovered
        result['checks']['recall_after_actual_restart'] = True
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
        print('PASS: previous player and real memory restored; ' + str(args.output))
        return
    player = 'validation-' + uuid4().hex
    other = player + '-other'
    first = post('/recall', {'player_id': player, 'query': '杂货铺'})
    assert first['status'] == 'empty', first
    action = '我把借口罐头偷偷换成了空气，标签写着量子罐头。'
    # Fixture only, deliberately not claiming this line came from a model.
    reply = '乌老板敲了敲空罐：好一个量子罐头！你的恶作剧我记下了。'
    saved = post('/remember', {'player_id': player, 'query': action, 'reply': reply})
    assert saved['records'], saved
    for record in saved['records']:
        assert record['artifact']['family'] == 'atomic-memory'
        assert record['artifact']['artifact_id'] and record['artifact']['revision'] >= 1
    recovered = post('/recall', {'player_id': player, 'query': '我又来杂货铺了，你认识我吗？'})
    assert recovered['scope_id'] == first['scope_id']
    assert recovered['status'] == 'ready', recovered
    assert '量子罐头' in recovered['content'], recovered
    repeated = post('/remember', {'player_id': player, 'query': action, 'reply': reply})
    assert repeated['scope_id'] == first['scope_id'] and repeated['records']
    isolated = post('/recall', {'player_id': other, 'query': '杂货铺'})
    assert isolated['status'] == 'empty', isolated
    assert isolated['scope_id'] != first['scope_id']
    try:
        post('/recall', {'player_id': player, 'query': '杂货铺'}, 'wrong-token')
        raise AssertionError('unauthorized request unexpectedly accepted')
    except HTTPError as error:
        assert error.code == 401
    result = {'tested': 'real PowerContext HTTP memory roundtrip + player isolation + gateway auth',
              'player_id': player,
              'model_reply_origin': 'fixed test fixture; no Dify/model end-to-end claim',
              'initial': first, 'write': saved, 'new_request_recall': recovered, 'other_player': isolated,
              'checks': {'empty_initial':True,'write_evidence':True,'recall_previous_action':True,
                         'player_isolation':True,'reject_bad_token':True,'repeat_input':True}}
    output = args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
    print('PASS: real persistence, recall, repeated input, player isolation, authentication; ' + str(output))

if __name__ == '__main__':
    main()
